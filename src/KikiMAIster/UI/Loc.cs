    {
        "fr" => true,
        "en" => false,
        _ => LocManager.Instance?.Language == "fra"
    };

    public static bool Has(string key) => Strings.ContainsKey(key);

    public static string T(string key) =>
        Strings.TryGetValue(key, out var s) ? (French ? s.Fr : s.En) : key;
